#!/usr/bin/env node
// Generates src/Rubrics.html from docs/G8_PE_Rubric_Bank.md so the app never
// hand-copies rubric wording. v1 needs the nine fundamental-skill ladders.
// Run: node dev/build-rubrics.js   (also run by build-preview / build-single)
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const md = fs.readFileSync(path.join(root, 'docs/G8_PE_Rubric_Bank.md'), 'utf8');

const KEYS = { 'Throw': 'throw', 'Catch': 'catch', 'Strike': 'strike', 'Dribble': 'dribble', 'Kick': 'kick', 'Jump & land': 'jump', 'Core stability': 'core' };
const LEVELS = 6;
const ladders = {};
const sec = md.split('## Fundamental Skills')[1].split('\n## ')[0];
sec.split('\n').forEach(line => {
  const m = line.match(/^\|\s*\*\*(.+?)\*\*\s*\|(.+)\|\s*$/);
  if (!m) return;
  const name = m[1].trim(), key = KEYS[name];
  if (!key) throw new Error('Unknown skill in rubric bank: ' + name);
  const levels = m[2].split('|').map(s => s.trim()).filter(Boolean);
  if (levels.length !== LEVELS) throw new Error(name + ': expected ' + LEVELS + ' levels, got ' + levels.length);
  ladders[key] = { name, levels };
});
if (Object.keys(ladders).length !== 7) throw new Error('Expected 7 ladders, got ' + Object.keys(ladders).length);

// Unit rubrics: each "## N · <Family> — <Unit>" section with "### <Criterion> — <standard>" tables,
// bands written as 7 / 5–6 / 3–4 / 1–2. Output criteria bottom-up: [Beginning, Intermediate, Proficient, Advanced].
// Only the units the app shows are required; add a key here to surface another unit.
const UNIT_KEYS = { 'Badminton': 'badminton' };
const BAND_ORDER = ['1–2', '3–4', '5–6', '7'];
const units = {};
md.split('\n## ').forEach(block => {
  const head = block.split('\n')[0];
  const um = head.match(/—\s*(.+?)\s*$/); if (!um) return;
  const key = UNIT_KEYS[um[1].trim()]; if (!key) return;
  const criteria = [];
  block.split('\n### ').slice(1).forEach(c => {
    const lines = c.split('\n'), ch = lines[0].match(/^(.+?)\s+—\s+(PE\.[\w.-]+)/); if (!ch) return;
    const bands = {};
    lines.forEach(l => { const m = l.match(/^\|\s*\*\*(.+?)\*\*\s*\|\s*(.+?)\s*\|\s*$/); if (m) bands[m[1].replace(/-/g, '–')] = m[2].replace(/\.$/, ''); });
    const levels = BAND_ORDER.map(b => bands[b]);
    if (levels.some(x => !x)) throw new Error(um[1] + ' / ' + ch[1] + ': expected bands ' + BAND_ORDER.join(', '));
    criteria.push({ name: ch[1].trim(), std: ch[2].replace(/^PE\.G6-10\./, ''), levels });
  });
  if (!criteria.length) throw new Error('No criteria found for unit ' + um[1]);
  units[key] = { name: um[1].trim(), criteria };
});
Object.keys(UNIT_KEYS).forEach(n => { if (!units[UNIT_KEYS[n]]) throw new Error('Unit not found in rubric bank: ' + n); });

// Active Participation: the five criteria of "## 1 · AP & Cooperation", bottom-up bands, keyed like the app.
const AP_CRIT = { 'Active Participation': 'effort', 'Social Skills': 'team', 'Self Management': 'ready', 'Growth Mindset': 'growth', 'Self Awareness': 'manage' };
const ap = {};
const apSec = md.split(/\n## 1 · AP & Cooperation/)[1];
if (!apSec) throw new Error('AP & Cooperation section not found in rubric bank');
apSec.split(/\n## /)[0].split('\n### ').slice(1).forEach(c => {
  const lines = c.split('\n'), name = lines[0].split('—')[0].trim(), key = AP_CRIT[name]; if (!key) return;
  const bands = {}, mine = {};
  lines.forEach(l => { const cells = l.split('|').map(x => x.trim()); const b = (cells[1] || '').match(/^\*\*(.+?)\*\*$/); if (b && cells[2]) { const k = b[1].replace(/-/g, '–'); bands[k] = cells[2].replace(/\.$/, ''); if (cells[3]) mine[k] = cells[3].replace(/\*/g, '').replace(/\.$/, ''); } });
  const levels = BAND_ORDER.map(b => bands[b]);
  if (levels.some(x => !x)) throw new Error('AP / ' + name + ': expected bands ' + BAND_ORDER.join(', '));
  // student: the "I…" column, bottom-up like levels (null where the bank has none)
  const student = BAND_ORDER.map(b => mine[b] || null), code = ((lines[0].match(/—\s*([A-Z][\w.-]+)/) || [])[1]) || '';
  ap[key] = { name, code, levels, student };
});
Object.keys(AP_CRIT).forEach(n => { if (!ap[AP_CRIT[n]]) throw new Error('AP criterion not found in rubric bank: ' + n); });

const out = '<script>\n// GENERATED by dev/build-rubrics.js from docs/G8_PE_Rubric_Bank.md — do not edit.\n' +
  'window.RUBRICS = ' + JSON.stringify({ ladders, units, ap }, null, 1).replace(/<\/script>/g, '<\\/script>') + ';\n</script>\n';
fs.writeFileSync(path.join(root, 'src/Rubrics.html'), out);
console.log('Wrote src/Rubrics.html', Object.keys(ladders).join(', '), '| ap:', Object.keys(ap).join(', '), '| units:', Object.keys(units).map(k => k + ' (' + units[k].criteria.map(c => c.name).join(', ') + ')').join('; '));
